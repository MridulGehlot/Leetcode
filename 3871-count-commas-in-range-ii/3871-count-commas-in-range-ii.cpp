class Solution {
public:
    long long countCommas(long long n) {
        if(n<=999) return 0;
        if(n<=999999) return n-999;
        if(n<=999999999) return (999999-999)*1+(n-999999)*2;
        if(n<=999999999999) return (999999-999)*1+(999999999-999999)*2+(n-999999999)*3;
        if(n<=999999999999999) return (999999-999)*1+(999999999-999999)*2+(999999999999-999999999)*3+(n-999999999999)*4;
        return (999999-999)*1+(999999999-999999)*2+(999999999999-999999999)*3+(999999999999999-999999999999)*4 + (n-999999999999999)*5 ;
    }
};